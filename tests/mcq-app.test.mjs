import {installOverlayGlobals} from './dom-overlays.mjs';
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { JSDOM } from "jsdom";
import "fake-indexeddb/auto";
import React, { act } from "react";
import { empty, save, load, getAssets, withNodes } from "./.build/data.mjs";
import { bullet } from "../src/domain.mjs";

const dom = new JSDOM('<div id="root"></div>', { url: "http://localhost", pretendToBeVisual: true });
for (const key of ["window", "document", "navigator", "HTMLElement", "HTMLInputElement", "HTMLTextAreaElement", "HTMLSelectElement", "Node", "DOMParser", "MutationObserver", "getComputedStyle"])
  Object.defineProperty(globalThis, key, { value: key === "getComputedStyle" ? dom.window.getComputedStyle.bind(dom.window) : dom.window[key], configurable: true });
installOverlayGlobals(dom);
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
globalThis.ResizeObserver = undefined;
globalThis.requestAnimationFrame = window.requestAnimationFrame.bind(window);
globalThis.cancelAnimationFrame = window.cancelAnimationFrame.bind(window);
window.matchMedia = () => ({ matches: true, addEventListener() {}, removeEventListener() {} });
HTMLElement.prototype.scrollTo = function ({ top = 0 }) { this.scrollTop = top; };
dom.window.HTMLDialogElement.prototype.showModal = function () { this.setAttribute("open", ""); };
dom.window.HTMLDialogElement.prototype.close = function () { this.removeAttribute("open"); };
const wait = async check => { for (let i = 0; i < 100; i++) { if (check()) return; await act(async () => { await new Promise(resolve => setTimeout(resolve, 20)); }); } throw Error("Timed out waiting for MCQ UI"); };
const click = async element => { assert.ok(element); await act(async () => { element.click(); }); };
const button = text => [...document.querySelectorAll("button")].find(element => element.textContent.trim().endsWith(text));

test("configure a four-child MCQ, study choices, resume feedback, practice misses and save custom GIFs", async () => {
  const doc = withNodes(empty(), [bullet("notebook", { text: "Science" }), bullet("q", { parentId: "notebook", text: "Which color is the sky?" }), ...["Blue", "Red", "Green", "Purple"].map((text, i) => bullet(`choice-${i}`, { parentId: "q", position: i, text })), bullet('bulk-q', { parentId: 'notebook', position: 1, text: 'Which planet is home?' }), ...['Venus', 'Earth @Answer', 'Mars', 'Jupiter'].map((text, i) => bullet(`bulk-option-${i}`, { parentId: 'bulk-q', position: i, text }))]);
  doc.web.quizReactions = { enabled: false, wrong: [{ path: 'media/quiz-missing.gif', label: 'missing-file-name' }] };
  await save(null, doc);
  let app;
  await act(async () => { app = await import("./.build/app.mjs"); });
  await wait(() => document.querySelector('[data-node-id="q"]'));
  const nested = document.querySelector('[data-node-id="choice-0"]');
  assert.ok(nested.querySelector('.outline-gutter > .row-hover-more'), "Each nested bullet owns its action gutter");
  assert.equal(nested.querySelector('.row-hover-more').style.left, '-28px', "Leaf dots sit immediately beside the child bullet");
  await click(document.querySelector('[data-node-id="q"] .row-hover-more'));
  await click(document.querySelector('[data-category="4"]'));
  await click(button("Turn into MCQ…"));
  await wait(() => document.querySelector('.mcq-editor[open]'));
  assert.equal(document.querySelectorAll('.mcq-answer-picker input').length, 4);
  assert.ok(button("Save MCQ").disabled);
  await click(document.querySelector('input[value="choice-0"]'));
  await click([...document.querySelectorAll('.mcq-editor .mcq-setting input')].at(-1));
  await act(async () => {
    const area = document.querySelector('[aria-label="Answer explanation"]');
    Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, 'value').set.call(area, 'A clear daytime sky appears blue.');
    area.dispatchEvent(new window.Event('input', { bubbles: true }));
  });
  await click(button("Save MCQ"));
  await wait(() => !document.querySelector('.mcq-editor'));
  await act(async () => { await new Promise(resolve => setTimeout(resolve, 250)); });
  let stored = await load();
  assert.equal(stored.web.mcqs.q.correctOptionId, 'choice-0');
  assert.equal(stored.web.mcqs.q.explanation, 'A clear daytime sky appears blue.');
  assert.equal(stored.web.deckTypes.q, 'MCQ');
  const originalSchedule = stored.tables.cards.find(card => card.id === 'q').dueAtEpochMillis;
  await click([...document.querySelectorAll('.sidebar nav button')].find(element => element.textContent.includes('Study Desk')));
  assert.ok(document.querySelector('.mcq-deck-badge'));
  assert.equal(document.querySelector('[aria-label="Open All flashcards notebook"]').disabled, true, 'An MCQ-only workspace has no flashcards to study');
  assert.equal(document.querySelector('[aria-label="Open All MCQs notebook"]').disabled, false, 'MCQs remain available in their own collection');
  await click(button('Cram'));
  const article = [...document.querySelectorAll('.study-deck')].find(article => article.querySelector('h2').textContent === 'Which color is the sky?');
  await click(article.querySelector('.study-primary'));
  assert.equal(document.querySelectorAll('.mcq-option').length, 4);
  assert.equal(document.querySelector('.flashcard-answer'), null);
  assert.equal(document.querySelector('.mcq-feedback'), null);
  const choiceOrder = [...document.querySelectorAll('.mcq-option')].map(element => element.getAttribute('aria-label'));
  await click([...document.querySelectorAll('.mcq-option')].find(element => element.textContent.includes('Red')));
  assert.equal(document.querySelectorAll('.mcq-option.is-wrong').length, 1);
  assert.equal(document.querySelectorAll('.mcq-option.is-correct').length, 1);
  assert.match(document.querySelector('.mcq-explanation').textContent, /daytime sky appears blue/);
  assert.ok(document.querySelector('.study-reaction-rail.reaction-right'), 'Wrong reactions use the right rail');
  assert.ok(document.querySelector('.quiz-reaction img'), 'Answer GIF auto-plays even with reduced motion and legacy disabled setting');
  assert.equal(button('Play GIF'), undefined, 'No play button is needed');
  assert.doesNotMatch(document.querySelector('.quiz-reaction').textContent, /missing-file-name/, 'A filename is not feedback');
  assert.ok(document.querySelector('.quiz-reaction img').src.endsWith('.gif'));
  assert.doesNotMatch(document.querySelector('.quiz-reaction img').src, /quiz-missing/, 'Missing custom GIF uses a bundled fallback');
  await act(async () => { await new Promise(resolve => setTimeout(resolve, 4200)); });
  assert.ok(document.querySelector('.quiz-reaction img'), 'Reaction remains available after four seconds');
  await click(button('Hide GIF'));
  assert.equal(document.querySelector('.quiz-reaction img'), null);
  assert.ok([...document.querySelectorAll('.mcq-option')].every(element => element.disabled));
  await click(document.querySelector('.session-controls > button'));
  await click(document.querySelector('.study-resume button'));
  assert.deepEqual([...document.querySelectorAll('.mcq-option')].map(element => element.getAttribute('aria-label')), choiceOrder);
  assert.ok(document.querySelector('.mcq-option.is-wrong'), 'First attempt survives pausing/resuming');
  await click(document.querySelector('[data-mcq-continue]'));
  assert.equal(document.querySelector('.mcq-score > strong').textContent, '0 / 1');
  await click(button('Practice 1 missed questions'));
  await click([...document.querySelectorAll('.mcq-option')].find(element => element.textContent.includes('Blue')));
  assert.ok(document.querySelector('.quiz-reaction.is-correct'));
  assert.ok(document.querySelector('.quiz-reaction img'), 'The next answer automatically starts a new GIF after hiding the previous one');
  assert.ok(document.querySelector('.study-reaction-rail.reaction-left'), 'Correct reactions use the left rail');
  await click(document.querySelector('[data-mcq-continue]'));
  assert.equal(document.querySelector('.mcq-score > strong').textContent, '1 / 1');
  await click(button('Back to Study Desk'));
  await click(button('Quiz reactions'));
  await wait(() => document.querySelector('.quiz-settings[open]'));
  const gif = await readFile(new URL('../src/assets/reactions/victory-wiggle.gif', import.meta.url));
  const upload = document.querySelector('.quiz-settings input[type="file"]');
  Object.defineProperty(upload, 'files', { configurable: true, value: [new File([gif], 'party.gif', { type: 'image/gif' })] });
  await act(async () => upload.dispatchEvent(new window.Event('change', { bubbles: true })));
  await click(button('Save reactions'));
  await wait(() => !document.querySelector('.quiz-settings'));
  stored = await load();
  assert.equal(stored.web.quizReactions.enabled, true);
  assert.equal(stored.web.quizReactions.correct.length, 1);
  assert.ok((await getAssets()).has(stored.web.quizReactions.correct[0].path));
  assert.equal(stored.tables.cards.find(card => card.id === 'q').dueAtEpochMillis, originalSchedule, 'Cram and missed-question practice do not reschedule');
  assert.equal(stored.tables.review_logs.length, 2);
  await click([...document.querySelectorAll('.sidebar nav button')].find(element => element.textContent.startsWith('Notes')));
  await click(document.querySelector('[data-node-id="notebook"] .row-hover-more'));
  await click(document.querySelector('[data-category="4"]'));
  await click(button('Make MCQ notebook'));
  await wait(() => document.querySelector('#bulk-mcq-title'));
  assert.match(document.querySelector('.bulk-mcq-summary').textContent, /2 ready/);
  await click(button('Convert 2 questions'));
  await wait(() => !document.querySelector('#bulk-mcq-title'));
  await act(async () => { await new Promise(resolve => setTimeout(resolve, 250)); });
  stored = await load();
  assert.equal(stored.web.mcqs['bulk-q'].correctOptionId, 'bulk-option-1');
  assert.equal(stored.web.deckTypes.notebook, 'MCQ');
  await click([...document.querySelectorAll('.sidebar nav button')].find(element => element.textContent.includes('Study Desk')));
  assert.ok([...document.querySelectorAll('.study-deck h2')].some(heading => heading.textContent === 'All MCQs'));
  await click(button('Cram'));
  const allMcqs = [...document.querySelectorAll('.study-deck')].find(article => article.querySelector('h2').textContent === 'All MCQs');
  assert.match(allMcqs.querySelector('.study-deck-counts').textContent, /2 cards/);
  await click([...allMcqs.querySelectorAll('button')].find(element => element.textContent === 'Review settings'));
  assert.equal(document.querySelectorAll('.study-limits').length, 1, 'Only the selected default notebook opens its limits panel');
  assert.equal(allMcqs.querySelector('[title="Open deck source"]'), null, 'Default MCQ deck has no fake source link');
  await click(allMcqs.querySelector('.study-primary'));
  await click([...document.querySelectorAll('.mcq-option')].find(element => element.textContent.includes('Blue')));
  await click(document.querySelector('[data-mcq-continue]'));
  assert.ok(document.querySelector('.mcq-options').textContent.includes('Earth'));
  assert.ok(!document.querySelector('.mcq-options').textContent.includes('@Answer'), 'Answer marker never leaks during study');
  await act(async () => app.appRoot.unmount());
  dom.window.close();
});
