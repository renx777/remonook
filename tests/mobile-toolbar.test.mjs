import {test} from 'node:test';
import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import React,{act} from 'react';
import {Editor} from '@tiptap/core';
import StarterKit from '@tiptap/starter-kit';
import {MobileEditToolbar} from './.build/MobileEditToolbar.mjs';
import {RemoColor,RemoHighlight,RemoMask} from './.build/editor.mjs';
const dom=new JSDOM('<div id="editor"></div><div id="toolbar"></div>',{url:'http://localhost',pretendToBeVisual:true});
for(const key of ['window','document','navigator','Node','HTMLElement','HTMLInputElement','MutationObserver','DOMParser','getComputedStyle'])Object.defineProperty(globalThis,key,{value:key==='getComputedStyle'?dom.window[key].bind(dom.window):dom.window[key],configurable:true});
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
globalThis.requestAnimationFrame=window.requestAnimationFrame.bind(window);
globalThis.cancelAnimationFrame=window.cancelAnimationFrame.bind(window);
window.scrollBy=()=>{};
const media=new window.EventTarget();media.matches=true;window.matchMedia=()=>media;
const viewport=new window.EventTarget();viewport.height=window.innerHeight;viewport.offsetTop=0;
Object.defineProperty(window,'visualViewport',{value:viewport});
const {createRoot}=await import('react-dom/client');
const click=async name=>act(async()=>document.querySelector(`[aria-label="${name}"]`).click());
test('mobile editing retains selections, sets typing colors, dispatches hierarchy commands and follows keyboard viewport',async()=>{
 const editor=new Editor({element:document.getElementById('editor'),extensions:[StarterKit,RemoColor,RemoHighlight,RemoMask],content:'<p>Remember this</p>'});
 editor.view.coordsAtPos=()=>({left:20,right:20,top:80,bottom:100});
 const commands=[];let finished=false;
 const root=createRoot(document.getElementById('toolbar'));
 await act(async()=>root.render(React.createElement(MobileEditToolbar,{editor,disabled:false,formattingDisabled:false,blockStyle:'paragraph',onCommand:x=>commands.push(x),onDone:()=>{finished=true;}})));
 assert.ok(document.querySelector('[aria-label="Mobile editing tools"]'));
 await act(async()=>editor.commands.setTextSelection({from:1,to:9}));
 await click('Bold');assert.ok(editor.isActive('bold'));assert.deepEqual([editor.state.selection.from,editor.state.selection.to],[1,9]);
 await click('Indent bullet');await click('Outdent bullet');assert.deepEqual(commands,['indent','outdent']);
 await act(async()=>editor.commands.setTextSelection(14));
 await click('Blue text');assert.equal(editor.getAttributes('remoColor').value,'2463BB');
 await act(async()=>editor.commands.insertContent('!'));assert.match(editor.getHTML(),/2463BB/);
 await act(async()=>{viewport.height=window.innerHeight-300;viewport.dispatchEvent(new window.Event('resize'));});
 assert.equal(document.querySelector('.mobile-edit-dock').style.bottom,'300px');
 assert.equal(document.querySelector('.mobile-edit-dock').dataset.keyboard,'true');
 await act(async()=>{viewport.height=window.innerHeight;viewport.dispatchEvent(new window.Event('resize'));});
 assert.equal(document.querySelector('.mobile-edit-dock').style.bottom,'0px');
 await click('Finish editing');assert.equal(finished,true);
 await act(async()=>{media.matches=false;media.dispatchEvent(new window.Event('change'));});
 assert.equal(document.querySelector('.mobile-edit-dock'),null);
 await act(async()=>{root.unmount();editor.destroy();});dom.window.close();
});
