test('mindmap branches expand, collapse, rename, add and delete nodes', async () => {
  await save(await load(), withNodes(empty(), [bullet('top', { text: 'Top' }), bullet('plan', { parentId: 'top', text: 'Plan', mindmap: true }), bullet('a', { parentId: 'plan', text: 'Alpha' }), bullet('b', { parentId: 'a', text: 'Beta' }), bullet('c', { parentId: 'plan', position: 1, text: 'Charlie' })])); let app;
  const settle = async () => act(async () => { await new Promise(resolve => setTimeout(resolve, 350)); });
  const node = id => document.querySelector(`.react-flow__node[data-id="${id}"]`);
  const setInput = async value => act(async () => {
    const input = document.querySelector('.mind-input');
    Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, 'value').set.call(input, value);
    input.dispatchEvent(new window.Event('input', { bubbles: true }));
  });
  const inputKey = async key => act(async () => document.querySelector('.mind-input').dispatchEvent(new window.KeyboardEvent('keydown', { key, bubbles: true, cancelable: true })));
  const dblclick = async selector => act(async () => document.querySelector(selector).dispatchEvent(new window.MouseEvent('dblclick', { bubbles: true })));
  try {
    await act(async () => { app = await import('./.build/app.mjs?interactive=1'); });
    await wait(() => document.querySelector('[data-node-id="plan"]'));
    await click('[data-node-id="plan"] .bullet-mindmap-open'); await wait(() => document.querySelector('.mindmap-view'));
    assert.equal(document.querySelectorAll('.mind-node').length, 4, 'tree renders root plus children');
    await click('.react-flow__node[data-id="plan"] .mind-toggle');
    await wait(() => document.querySelectorAll('.mind-node').length === 1);
    assert.equal(document.querySelector('.react-flow__node[data-id="plan"] .mind-hidden-count').textContent, '3', 'collapsed node shows hidden branch size');
    await click('.react-flow__node[data-id="plan"] .mind-toggle');
    await wait(() => document.querySelectorAll('.mind-node').length === 4);
    await click('[aria-label="Collapse all"]');
    await wait(() => document.querySelectorAll('.mind-node').length === 1);
    await click('[aria-label="Expand all"]');
    await wait(() => document.querySelectorAll('.mind-node').length === 4);
    await click('.react-flow__node[data-id="a"] .mind-toggle');
    await wait(() => document.querySelectorAll('.mind-node').length === 3);
    await click(navButton('Notes')); await wait(() => document.querySelector('[data-node-id="a"]'));
    assert.equal(document.querySelector('[data-node-id="b"]'), null, 'collapse in the mindmap hides the branch in the outline too');
    await click('[data-node-id="plan"] .bullet-mindmap-open'); await wait(() => document.querySelectorAll('.mind-node').length === 3);
    await click('.react-flow__node[data-id="a"] .mind-toggle');
    await wait(() => document.querySelectorAll('.mind-node').length === 4);
    await click('.react-flow__node[data-id="b"] [aria-label="Add child"]');
    await wait(() => document.querySelector('.mind-input'));
    await setInput('Beta child'); await inputKey('Enter');
    await wait(() => [...document.querySelectorAll('.mind-label')].some(label => label.textContent === 'Beta child'));
    await settle();
    let doc = await load();
    const betaChild = doc.tables.bullets.find(n => n.text === 'Beta child');
    assert.ok(betaChild, 'new child is persisted');
    assert.equal(betaChild.parentId, 'b', 'new child is nested under its parent');
    await click('.react-flow__node[data-id="b"] [aria-label="Add sibling below"]');
    await wait(() => document.querySelector('.mind-input'));
    await setInput('After B'); await inputKey('Enter');
    await wait(() => [...document.querySelectorAll('.mind-label')].some(label => label.textContent === 'After B'));
    await settle();
    doc = await load();
    const afterB = doc.tables.bullets.find(n => n.text === 'After B');
    assert.ok(afterB, 'new sibling is persisted');
    assert.equal(afterB.parentId, 'a', 'new sibling shares the parent');
    assert.equal(afterB.position, 1, 'new sibling sits after its anchor');
    await dblclick('.react-flow__node[data-id="c"] .mind-node');
    await wait(() => document.querySelector('.mind-input'));
    await setInput('Charlie C'); await inputKey('Enter');
    await wait(() => [...document.querySelectorAll('.mind-label')].some(label => label.textContent === 'Charlie C'));
    await settle();
    doc = await load();
    assert.equal(doc.tables.bullets.find(n => n.id === 'c').text, 'Charlie C', 'rename is persisted');
    await click('.react-flow__node[data-id="b"] [aria-label="Delete branch"]');
    await wait(() => node('b').querySelector('.mind-node.is-confirm'));
    assert.ok(node('b').textContent.includes('Delete branch?'), 'delete asks for confirmation');
    await click('.react-flow__node[data-id="b"] .mind-danger');
    await wait(() => !node('b'));
    await settle();
    doc = await load();
    assert.equal(doc.tables.bullets.some(n => n.id === 'b'), false, 'deleted branch is gone');
    assert.equal(doc.tables.bullets.some(n => n.text === 'Beta child'), false, 'descendants go with the deleted branch');
    await click('.react-flow__node[data-id="a"] .mind-node');
    await wait(() => node('a').querySelector('.mind-node.is-selected'));
    assert.equal(navButton('Mindmap').getAttribute('aria-current'), 'page', 'clicking selects the node without leaving the mindmap');
    await click('.react-flow__node[data-id="a"] [aria-label="Open in Notes"]');
    await wait(() => document.querySelector('.zoomed-title'));
    assert.equal(document.querySelector('.zoomed-title').value, 'Alpha', 'Open in Notes opens its bullet in Notes');
    assert.equal(navButton('Notes').getAttribute('aria-current'), 'page');
  } finally { if (app) await act(async () => app.appRoot.unmount()); dom.window.close(); }
});
