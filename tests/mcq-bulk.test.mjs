test("10,000 nesting levels remain traversable, convertible and readable without a fixed indentation cutoff", () => {
  const nodes = [];
  for (let i = 0; i < 10000; i++) nodes.push(bullet(`level${i}`, { parentId: i ? `level${i - 1}` : null, text: `Level ${i}`, collapsed: false }));
  nodes.push(...question('deep-question', 'level9999'));
  let doc = withNodes(empty(), nodes);
  assert.equal(bulkMcqPlan(doc, 'level0').ready.length, 1);
  doc = configureMcqBranch(doc, 'level0'); doc = withNodes(doc, doc.tables.bullets);
  assert.equal(indexedRows(index(doc.tables.bullets), null, true).at(-1).depth, 10001);
  assert.equal(scopedCards(doc, 'level0').length, 1);
  for (const width of [320, 390, 768, 1440]) {
    assert.ok(depthIndent(9, width) > depthIndent(8, width));
    assert.ok(depthIndent(10000, width) > depthIndent(1000, width));
    assert.ok(Number.isFinite(depthIndent(10000, width)));
    assert.ok(width - depthIndent(10000, width) > 140, 'Compressed indentation preserves room for text');
  }
});

test("a 10,000-flashcard deck accepts more cards without truncating its queue", () => {
  const nodes = [bullet('deck', { text: 'Large flashcard deck' })];
  for (let i = 0; i < 10000; i++) nodes.push(bullet(`f${i}`, { parentId: 'deck', position: i, kind: 'QUESTION', text: `Question ${i}` }), bullet(`a${i}`, { parentId: `f${i}`, text: `Answer ${i}` }));
  const initial = empty(); initial.tables.decks.push({ rootId: 'deck', createdAt: 1, pinned: 0 });
  let doc = withNodes(initial, nodes);
  assert.equal(doc.tables.cards.length, 10000);
  doc = withNodes(doc, [...nodes, bullet('extra', { parentId: 'deck', position: 10000, kind: 'QUESTION', text: 'One more question' }), bullet('extra-answer', { parentId: 'extra', text: 'One more answer' })]);
  assert.equal(doc.tables.cards.length, 10001);
  assert.equal(JSON.parse(newStudySession(doc, 'deck', 'NORMAL').queueJson).length, 10001);
});
