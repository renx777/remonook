const question = (id, parentId = null, answer = 1) => [bullet(id, { parentId, text: `Question ${id}`, collapsed: true }), ...[0, 1, 2, 3].map(i => bullet(`${id}-${i}`, { parentId: id, position: i, text: `Choice ${i}${i === answer ? ' @Answer' : ''}` }))];

test("bulk conversion scans collapsed nested branches, skips ambiguous keys and is idempotent", () => {
  let doc = withNodes(empty(), [bullet('deck', { text: 'Biology', collapsed: true }), ...question('q', 'deck'), bullet('nested', { text: 'Chapter', parentId: 'deck', position: 1, collapsed: true }), ...question('q2', 'nested'), ...question('missing', 'deck', -1), ...question('ambiguous', 'deck'), ...question('empty', 'deck')]);
  doc.tables.bullets.find(node => node.id === 'ambiguous-0').text += ' @answer';
  doc.tables.bullets.find(node => node.id === 'empty-1').text = '@Answer';
  const before = JSON.stringify(doc.tables.bullets), plan = bulkMcqPlan(doc, 'deck');
  assert.deepEqual(new Set(plan.ready.map(item => item.id)), new Set(['q', 'q2']));
  assert.equal(plan.skipped.length, 3);
  assert.match(plan.skipped.find(item => item.id === 'ambiguous').reason, /More than one/);
  assert.equal(JSON.stringify(doc.tables.bullets), before, 'Preview is read-only');
  doc = configureMcqBranch(doc, 'deck', 123);
  doc = withNodes(doc, doc.tables.bullets);
  assert.equal(doc.web.mcqs.q.correctOptionId, 'q-1');
  assert.equal(doc.web.deckTypes.deck, 'MCQ');
  assert.equal(doc.tables.cards.filter(card => card.state === 'ACTIVE').length, 2, 'No accidental Q&A cards generated by the MCQ container');
  const original = doc.tables.cards.find(card => card.id === 'q');
  original.dueAtEpochMillis = 123456789; original.repetitionCount = 5;
  const again = withNodes(configureMcqBranch(doc, 'deck', 456), doc.tables.bullets);
  assert.equal(again.tables.decks.length, 1);
  assert.equal(again.tables.cards.find(card => card.id === 'q').dueAtEpochMillis, 123456789);
  assert.equal(again.tables.cards.find(card => card.id === 'q').repetitionCount, 5);
  assert.ok(again.tables.bullets.find(node => node.id === 'q-1').text.includes('@Answer'), 'Source markers retained');
});

test("@Answer detection is case insensitive and study stripping preserves formatting offsets", () => {
  assert.deepEqual(taggedMcqAnswer([{ id: 'a', text: 'Blue @aNsWeR' }, { id: 'b', text: 'mail@Answer.com or @Answers' }]), { id: 'a', count: 1 });
  const node = bullet('option', { text: '@Answer Blue', formatting: '0:12:BOLD;8:12:COLOR_ffff00' }), clean = mcqStudyOption(node);
  assert.equal(clean.text, 'Blue');
  assert.equal(clean.formatting, '0:4:BOLD;0:4:COLOR_ffff00');
  assert.equal(node.text, '@Answer Blue');
  const doc = withNodes(empty(), question('single'));
  assert.equal(configureMcq(doc, 'single', {}).web.mcqs.single.correctOptionId, 'single-1');
});

test("All MCQs always includes standalone questions and named-deck questions, but not regular flashcards", () => {
  let doc = withNodes(empty(), [bullet('deck', { text: 'Notebook' }), ...question('inside', 'deck'), ...question('orphan'), bullet('regular', { text: 'Regular question', kind: 'QUESTION' }), bullet('answer', { text: 'Regular answer', parentId: 'regular' })]);
  doc = configureMcqBranch(doc, 'deck');
  doc = configureMcq(doc, 'orphan', {});
  doc = withNodes(doc, doc.tables.bullets);
  const now = Date.now() + 1000, context = createStudyContext(doc, now);
  assert.deepEqual(new Set(scopedCards(doc, ALL_MCQS, now, context).map(card => card.id)), new Set(['inside', 'orphan']));
  assert.deepEqual(scopedCards(doc, 'deck', now, context).map(card => card.id), ['inside']);
  assert.equal(scopedCards(doc, null, now, context).length, 3);
  assert.equal(dueCards(doc, ALL_MCQS, now, context).length, 2);
  assert.equal(JSON.parse(newStudySession(doc, ALL_MCQS, 'NORMAL', now).queueJson).length, 2);
  assert.equal(doc.tables.decks.some(deck => deck.rootId === 'orphan'), false, 'No one-question notebook is required');
});

test("an MCQ without markers keeps its existing key; invalid branches cannot silently create a deck", () => {
  let doc = withNodes(empty(), question('q', null, -1));
  assert.throws(() => configureMcqBranch(doc, 'q'), /No questions are ready/);
  doc = configureMcq(doc, 'q', { correctOptionId: 'q-2', explanation: 'Remember this', shuffle: false });
  const plan = bulkMcqPlan(doc, 'q');
  assert.equal(plan.ready[0].correctOptionId, 'q-2');
  const next = configureMcqBranch(doc, 'q');
  assert.equal(next.web.mcqs.q.explanation, 'Remember this');
  assert.equal(next.web.mcqs.q.shuffle, false);
});

