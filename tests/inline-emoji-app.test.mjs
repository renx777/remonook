import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { JSDOM } from 'jsdom';
import 'fake-indexeddb/auto';
import { act } from 'react';
import { empty, withNodes, save, load, getAssets } from './.build/data.mjs';
import { bullet } from '../src/domain.mjs';

const dom = new JSDOM('<div id="root"></div>', { url: 'http://localhost', pretendToBeVisual: true });
for (const key of ['window', 'document', 'navigator', 'HTMLElement', 'HTMLInputElement', 'HTMLTextAreaElement', 'HTMLSelectElement', 'Node', 'DOMParser', 'MutationObserver', 'getComputedStyle']) Object.defineProperty(globalThis, key, { value: key === 'getComputedStyle' ? dom.window.getComputedStyle.bind(dom.window) : dom.window[key], configurable: true });
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
globalThis.ResizeObserver = undefined;
globalThis.requestAnimationFrame = window.requestAnimationFrame.bind(window); globalThis.cancelAnimationFrame = window.cancelAnimationFrame.bind(window);
window.matchMedia = () => ({ matches: true, addEventListener() {}, removeEventListener() {} });
HTMLElement.prototype.scrollTo = function ({ top = 0 }) { this.scrollTop = top; };
dom.window.Range.prototype.getClientRects = () => [];
dom.window.Range.prototype.getBoundingClientRect = () => ({ left: 0, right: 0, top: 0, bottom: 0, width: 0, height: 0 });
dom.window.HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', ''); };
const wait = async check => { for (let i = 0; i < 150; i++) { if (check()) return; await act(async () => new Promise(resolve => setTimeout(resolve, 20))); } throw Error('Timed out waiting for inline emoji UI'); };
const key = async value => act(async () => document.querySelector('.tiptap').dispatchEvent(new window.KeyboardEvent('keydown', { key: value, bubbles: true, cancelable: true })));

test('colon picker supports keyboard insertion, caret continuation, offline reuse, dismissal and download errors', async () => {
  await save(null, withNodes(empty(), [bullet('inline', { text: 'Go ' })]));
  const originalFetch = globalThis.fetch;
  let requests = 0, app;
  globalThis.fetch = async url => { requests++; return new Response(await readFile(new URL(`./fixtures/noto/1f680.${url.endsWith('webp') ? 'webp' : 'svg'}`, import.meta.url))); };
  try {
    await act(async () => { app = await import('./.build/app.mjs'); });
    await wait(() => document.querySelector('[data-node-id="inline"] .text-button'));
    await act(async () => document.querySelector('[data-node-id="inline"] .text-button').click());
    await wait(() => document.querySelector('.tiptap'));
    const editor = document.querySelector('.tiptap').editor;
    const type = async text => act(async () => { editor.commands.focus(); editor.commands.insertContent(text); });
    await act(async () => editor.commands.setTextSelection(4));
    await type(':');
    await wait(() => document.querySelector('[aria-label="Emoji suggestions"]'));
    assert.equal(document.querySelectorAll('.inline-emoji-picker [role="option"]').length, 8);
    const first = document.querySelector('[aria-selected="true"]').id;
    await key('ArrowDown'); assert.notEqual(document.querySelector('[aria-selected="true"]').id, first);
    await key('ArrowUp'); assert.equal(document.querySelector('[aria-selected="true"]').id, first);
    await key('ArrowRight'); assert.notEqual(document.querySelector('[aria-selected="true"]').id, first);
    await key('ArrowLeft'); assert.equal(document.querySelector('[aria-selected="true"]').id, first);
    await type('rocket');
    assert.match(document.querySelector('.inline-emoji-picker [role="option"]').textContent, /Rocket/);
    assert.ok(document.querySelector('.tiptap').getAttribute('aria-activedescendant'));
    await key('Enter');
    await wait(() => !document.querySelector('.inline-emoji-picker'));
    assert.equal(requests, 2);
    assert.equal(document.querySelectorAll('.outline-row').length, 1, 'Enter inserts instead of splitting the bullet');
    assert.equal(editor.getText(), 'Go :noto_1f680:');
    assert.equal(editor.state.selection.from, editor.getText().length + 1);
    await type(' onward'); assert.equal(editor.getText(), 'Go :noto_1f680: onward');
    globalThis.fetch = async () => { throw Error('offline'); };
    await type(' :rocket'); await key('Tab'); await wait(() => !document.querySelector('.inline-emoji-picker'));
    assert.equal(editor.getText(), 'Go :noto_1f680: onward :noto_1f680:');
    assert.equal(document.querySelector('[data-node-id="inline"]').style.getPropertyValue('--depth'), '', 'Tab does not indent');
    await type(' :head_shake');
    assert.ok(document.querySelector('.inline-emoji-picker'), editor.getText());
    assert.match(document.querySelector('.inline-emoji-picker').textContent, /Head shake/);
    await key('Enter'); await wait(() => document.querySelector('.inline-emoji-picker [role="alert"]'));
    assert.match(document.querySelector('[role="alert"]').textContent, /connection/);
    assert.match(editor.getText(), /:head_shake$/, 'Failed downloads preserve the typed query');
    await key('Escape'); assert.equal(document.querySelector('.inline-emoji-picker'), null);
    assert.ok(document.querySelector('.tiptap'), 'Escape only closes suggestions, not editing');
    await type(' plain'); assert.equal(document.querySelector('.inline-emoji-picker'), null);
    await type(' :rocket');
    await act(async () => document.querySelector('.inline-emoji-picker [role="option"]').click());
    await wait(() => !document.querySelector('.inline-emoji-picker'));
    assert.match(editor.getText(), /plain :noto_1f680:$/);
    await act(async () => { editor.commands.setContent('<p>https:</p>'); editor.commands.setTextSelection(7); });
    assert.equal(document.querySelector('.inline-emoji-picker'), null);
    await act(async () => { editor.commands.setContent('<p><code>:rocket</code></p>'); editor.commands.setTextSelection(8); });
    assert.equal(document.querySelector('.inline-emoji-picker'), null, 'Code is left untouched');
    await act(async () => new Promise(resolve => setTimeout(resolve, 300)));
    assert.equal((await load()).tables.emojis.length, 1);
    assert.ok((await getAssets()).has('emoji/noto_1f680.svg'));
  } finally { globalThis.fetch = originalFetch; if (app) await act(async () => app.appRoot.unmount()); dom.window.close(); }
});
