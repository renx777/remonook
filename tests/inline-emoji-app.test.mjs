import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { JSDOM } from 'jsdom';
import 'fake-indexeddb/auto';
import { act } from 'react';
import { empty, withNodes, save, load, getAssets } from './.build/data.mjs';
import { bullet } from '../src/domain.mjs';

const dom = new JSDOM('<div id="root"></div>', { url: 'http://localhost', pretendToBeVisual: true });
for (const key of ['window', 'document', 'navigator', 'HTMLElement', 'HTMLInputElement', 'HTMLTextAreaElement', 'HTMLSelectElement', 'Node', 'DOMParser', 'MutationObserver', 'getComputedStyle']) Object.defineProperty(globalThis, key, { value: key === 'getComputedStyle' ? dom.window.getComputedStyle.bind(dom.window) : dom.window[key], configurable: true });
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
globalThis.ResizeObserver = undefined;
globalThis.requestAnimationFrame = window.requestAnimationFrame.bind(window); globalThis.cancelAnimationFrame = window.cancelAnimationFrame.bind(window);
window.matchMedia = query => ({ matches: query.includes('prefers-reduced-motion'), addEventListener() {}, removeEventListener() {} });
HTMLElement.prototype.scrollTo = function ({ top = 0 }) { this.scrollTop = top; };
dom.window.Range.prototype.getClientRects = () => [];
dom.window.Range.prototype.getBoundingClientRect = () => ({ left: 0, right: 0, top: 0, bottom: 0, width: 0, height: 0 });
dom.window.HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', ''); };
const wait = async check => { for (let i = 0; i < 150; i++) { if (check()) return; await act(async () => new Promise(resolve => setTimeout(resolve, 20))); } throw Error('Timed out waiting for inline emoji UI'); };
const key = async value => act(async () => document.querySelector('.tiptap').dispatchEvent(new window.KeyboardEvent('keydown', { key: value, bubbles: true, cancelable: true })));

test('colon picker supports keyboard insertion, caret continuation, offline reuse, dismissal and download errors', async () => {
  await save(null, withNodes(empty(), [bullet('inline', { text: 'Go ' })]));
  const originalFetch = globalThis.fetch;
  let requests = 0, app;
  const catalogFetch = async url => { requests++; return new Response(await readFile(new URL(`./fixtures/noto/1f680.${url.endsWith('webp') ? 'webp' : 'svg'}`, import.meta.url))); };
  globalThis.fetch = catalogFetch;
  try {
    await act(async () => { app = await import('./.build/app.mjs'); });
    await wait(() => document.querySelector('[data-node-id="inline"] .text-button'));
    await act(async () => document.querySelector('[data-node-id="inline"] .text-button').click());
    await wait(() => document.querySelector('.tiptap'));
    const editor = document.querySelector('.tiptap').editor;
    const type = async text => act(async () => { editor.commands.focus(); editor.commands.insertContent(text); });
    await act(async () => editor.commands.setTextSelection(4));
    await type(':');
    await wait(() => document.querySelector('[aria-label="Emoji suggestions"]'));
    assert.ok(document.querySelectorAll('.inline-emoji-picker [role="option"]').length>=48);
    assert.ok(document.querySelectorAll('.inline-emoji-picker [role="option"]').length<=81,'Only viewport rows and a small overscan are mounted');
    assert.equal(document.querySelector('.inline-emoji-picker [role="option"]').getAttribute('aria-setsize'),'881','All collection choices remain available');
    assert.equal(document.querySelectorAll('.inline-emoji-picker [role="tab"]').length, 3);
    assert.equal(document.querySelector('.inline-emoji-picker [role="tab"][aria-selected="true"]').textContent, 'Google Noto');
    assert.equal(document.querySelectorAll('.inline-emoji-results .animated-emoji').length, 0, 'Result tiles never create animation players');
    const originalCoordinates=editor.view.coordsAtPos;
    editor.view.coordsAtPos=()=>({left:100,right:100,top:140,bottom:160});
    Object.defineProperty(window,'visualViewport',{configurable:true,value:{width:390,height:300,offsetLeft:0,offsetTop:0,addEventListener(){},removeEventListener(){}}});
    await act(async()=>window.dispatchEvent(new window.Event('resize')));
    assert.equal(document.querySelector('.inline-emoji-picker').style.top,'8px','A short mobile keyboard viewport docks the panel into usable space');
    assert.equal(document.querySelector('.inline-emoji-picker').style.maxHeight,'284px');
    editor.view.coordsAtPos=originalCoordinates;delete window.visualViewport;
    await act(async()=>window.dispatchEvent(new window.Event('resize')));
    const resultGrid=document.querySelector('.inline-emoji-results');
    await act(async()=>{resultGrid.scrollTop=1200;resultGrid.dispatchEvent(new window.Event('scroll',{bubbles:true}));});
    assert.ok(Number(resultGrid.querySelector('[role="option"]').getAttribute('aria-posinset'))>100,'Scrolling exposes choices beyond the first results');
    assert.ok(resultGrid.querySelectorAll('[role="option"]').length<=81,'Scrolling keeps mounted results bounded');
    await act(async()=>document.querySelector('[aria-label="Food & drink"]').click());
    assert.match(document.querySelector('.inline-emoji-query').textContent,/Food & drink/);
    assert.ok(Number(resultGrid.querySelector('[role="option"]').getAttribute('aria-setsize'))>20);
    await act(()=>new Promise(resolve=>setTimeout(resolve,30))); // Settle Tiptap's initial animation-frame focus.
    const searchInside=async value=>act(async()=>{const input=document.querySelector('[aria-label="Search emoji"]');input.focus();Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,value);input.dispatchEvent(new window.Event('input',{bubbles:true}));});
    await searchInside('rocket');
    assert.match(document.querySelector('.inline-emoji-results').textContent,/Rocket/,'Panel search spans categories');
    assert.equal(document.activeElement?.getAttribute('aria-label'),'Search emoji','Panel search keeps keyboard focus');
    assert.equal(editor.getText(),'Go :','Panel search preserves the captured note shortcode');
    await searchInside('');
    await act(async()=>document.querySelector('[aria-label="All emojis"]').click());
    const first = document.querySelector('[role="option"][aria-selected="true"]').id;
    await key('ArrowDown'); assert.notEqual(document.querySelector('[role="option"][aria-selected="true"]').id, first);
    await key('ArrowUp'); assert.equal(document.querySelector('[role="option"][aria-selected="true"]').id, first);
    await key('ArrowRight'); assert.notEqual(document.querySelector('[role="option"][aria-selected="true"]').id, first);
    await key('ArrowLeft'); assert.equal(document.querySelector('[role="option"][aria-selected="true"]').id, first);
    window.matchMedia=()=>({matches:false,addEventListener(){},removeEventListener(){}});
    await type('rocket');
    assert.match(document.querySelector('.inline-emoji-picker [role="option"]').textContent, /Rocket/);
    assert.ok(document.querySelector('.tiptap').getAttribute('aria-activedescendant'));
    await wait(()=>document.querySelector('.inline-emoji-preview-animation'));
    const previewRequests=requests;let offlineAttempts=0;
    globalThis.fetch=async()=>{offlineAttempts++;throw Error('offline after preview');};
    await key('Enter');
    await wait(() => !document.querySelector('.inline-emoji-picker'));
    globalThis.fetch=catalogFetch;
    assert.ok(previewRequests>=2,'The preview fetched validated animation and poster bytes');
    assert.equal(requests,previewRequests);
    assert.equal(offlineAttempts,0,'Insertion reuses the validated preview without a second download');
    assert.equal(document.querySelectorAll('.outline-row').length, 1, 'Enter inserts instead of splitting the bullet');
    assert.equal(editor.getText(), 'Go :noto_1f680:');
    assert.equal(editor.state.selection.from, editor.getText().length + 1);
    await type(' onward'); assert.equal(editor.getText(), 'Go :noto_1f680: onward');
    globalThis.fetch = async () => { throw Error('offline'); };
    await type(' :rocket'); await key('Tab'); await wait(() => !document.querySelector('.inline-emoji-picker'));
    assert.equal(editor.getText(), 'Go :noto_1f680: onward :noto_1f680:');
    assert.equal(document.querySelector('[data-node-id="inline"]').style.getPropertyValue('--depth'), '', 'Tab does not indent');
    await type(' :head_shake');
    assert.ok(document.querySelector('.inline-emoji-picker'), editor.getText());
    assert.match(document.querySelector('.inline-emoji-picker').textContent, /Head shake/);
    await key('Enter'); await wait(() => document.querySelector('.inline-emoji-picker [role="alert"]'));
    assert.match(document.querySelector('[role="alert"]').textContent, /connection/);
    assert.match(editor.getText(), /:head_shake$/, 'Failed downloads preserve the typed query');
    await key('Escape'); assert.equal(document.querySelector('.inline-emoji-picker'), null);
    assert.ok(document.querySelector('.tiptap'), 'Escape only closes suggestions, not editing');
    await type(' plain'); assert.equal(document.querySelector('.inline-emoji-picker'), null);
    await type(' :rocket');
    const desktopMedia=window.matchMedia;
    window.matchMedia=query=>({matches:query.includes('pointer: coarse')||query.includes('prefers-reduced-motion'),addEventListener(){},removeEventListener(){}});
    await act(async () => document.querySelector('.inline-emoji-picker [role="option"]').click());
    assert.ok(document.querySelector('.inline-emoji-picker'),'A touch selection previews without inserting');
    assert.match(editor.getText(),/:rocket$/,'Touch preview preserves the typed shortcode');
    await act(async()=>document.querySelector('.inline-emoji-insert').click());
    window.matchMedia=desktopMedia;
    await wait(() => !document.querySelector('.inline-emoji-picker'));
    assert.match(editor.getText(), /plain :noto_1f680:$/);
    await type(' :');
    assert.equal(document.querySelector('.inline-emoji-results [role="option"] [data-emoji-token]').getAttribute('data-emoji-token'), ':noto_1f680:', 'Successful insertions lead the recent suggestions');
    const collection = name => [...document.querySelectorAll('.inline-emoji-tabs button')].find(button => button.textContent === name);
    await act(async()=>collection('My library').click());
    assert.ok(document.querySelector('.inline-emoji-results [data-emoji-token=":remo_smile:"]'), 'Custom emojis have their own library tab');
    await act(async()=>collection('Microsoft Fluent').click());
    await type('rocket');
    assert.equal(document.querySelectorAll('.inline-emoji-results [role="option"]').length,0);
    assert.match(editor.getText(),/:rocket$/,'Switching collections keeps the typed query');
    await act(async()=>document.querySelector('.inline-emoji-empty button').click());
    assert.equal(collection('Google Noto').getAttribute('aria-selected'),'true','Empty results offer the matching provider');
    await key('Escape');
    await act(async () => { editor.commands.setContent('<p>https:</p>'); editor.commands.setTextSelection(7); });
    assert.equal(document.querySelector('.inline-emoji-picker'), null);
    await act(async () => { editor.commands.setContent('<p><code>:rocket</code></p>'); editor.commands.setTextSelection(8); });
    assert.equal(document.querySelector('.inline-emoji-picker'), null, 'Code is left untouched');
    await act(async () => new Promise(resolve => setTimeout(resolve, 300)));
    assert.equal((await load()).tables.emojis.length, 1);
    assert.ok((await getAssets()).has('emoji/noto_1f680.svg'));
  } finally { globalThis.fetch = originalFetch; if (app) await act(async () => app.appRoot.unmount()); dom.window.close(); }
});
